const inter = Poppins({ subsets: ["latin"], weight: ["400", "700"] });

export const metadata = {
  title: "Amp Technology",
  description: "Generated by create next app",
};

async function getData() {
  try {
    const officeData = await fetch(`${process.env.BACKLINK}/public/officeData`, {
      headers: {
        "x-api-key": process.env.API_KEY,
        "office-id": process.env.OFFICE,
      },
      next: {
        revalidate: 60,
      },
    });

    if (!officeData.ok) {
      return console.error(`Failed to fetch office data: ${officeData.statusText}`);
    }

    return officeData.json();
  } catch (error) {
    console.error("Error:", error.message);
    return null;
  }
}

async function getLinks() {
  try {
    const links = await fetch(`${process.env.BACKLINK}/public/social`, {
      headers: {
        "x-api-key": process.env.API_KEY,
        "office-id": process.env.OFFICE,
      },
      cache: "no-store",
    });

    return await links.json();
  } catch (error) {
    return null;
  }
}

async function getBg() {
  try {
    const res = await fetch(process.env.BACKLINK + "/public/headings", {
      headers: {
        "x-api-key": process.env.API_KEY,
        "office-id": process.env.OFFICE,
      },
      next: { revalidate: 60 },
      signal: AbortSignal.timeout(5000),
    });
    if (!res.ok) return null;
    return await res.json();
  } catch (error) {
    console.error("[layout] getBg failed:", error.message);
    return null;
  }
}

export default async function RootLayout({ children }) {
  const data = await getData();
  const officeData = data?.data;
  const getSocial = await getLinks();
  const socialData = getSocial?.data[0];
  const bg = await getBg();

  return (
    <html lang="en">
      <body className={inter.className}>
        {/* <FirstVideo /> */}
        <Header
          data={officeData}
          links={socialData}
          bg={bg.data?.headerImage}
        />
        {/* <Arrowup /> */}
        {/* <WhatsAppButton /> */}
        {children}
        <Footer
          data={officeData}
          links={socialData}
          bg={bg.data?.footerImage}
        />
      </body>
    </html>
  );
}
